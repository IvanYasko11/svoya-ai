function providerDiagnostics(result) {
  const code=result.code||'PROVIDER_ERROR';
  const messages={
    NO_PROVIDER_CONFIGURED:['В этой версии сайта не настроен ключ ни одного LLM-провайдера.','Проверь OPENROUTER_API_KEY в Vercel для среды Preview и повторно разверни эту версию.'],
    ACCOUNT_QUOTA_EXHAUSTED:['Исчерпана бесплатная квота провайдера.','Попробуй после сброса квоты или подключи другой провайдер. Переключение free-моделей того же аккаунта не увеличивает дневную квоту.'],
    PROVIDER_TIMEOUT:['Модель не ответила вовремя.','Повтори запрос позже.'],
    PROVIDER_REQUEST_FAILED:['Сервер не смог подключиться к провайдеру.','Повтори позже; если ошибка сохраняется, проверь серверные журналы.']
  };
  let pair=messages[code];
  if(!pair)pair=({
    401:['Провайдер отклонил API-ключ.','Проверь действующий ключ в настройках Vercel.'],
    403:['Провайдер запретил доступ к запросу.','Проверь ограничения аккаунта, ключа и выбранной модели.'],
    402:['Провайдер требует доступный баланс или разрешённый лимит расходов.','Проверь баланс и модель. Покупка подписки ChatGPT не оплачивает API.'],
    404:['Выбранная модель или её endpoint недоступны.','Проверь название модели и доступные модели провайдера.'],
    429:['Провайдер ограничил частоту запросов или доступную квоту.','Подожди и повтори запрос; точный тип лимита нужно проверить у провайдера.'],
    503:['Провайдер временно недоступен.','Повтори запрос позже.']
  })[result.status]||['Не удалось получить ответ от модели.','Повтори позже или проверь настройки провайдера.'];
  return {error:pair[0],hint:pair[1],error_code:code,upstream_status:result.status};
}
module.exports={providerDiagnostics};
